"""Sync public evidence from a Heliox checkout; --check verifies without writing.

Usage: python scripts/sync_product_evidence.py --product ../cursor-os/pilot
The product generators must have been run first. No benchmark is rerun here.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = "https://raw.githubusercontent.com/VyomKulshrestha/Heliox-OS/main/docs/evidence/"


def outputs(product: Path) -> dict[str, bytes]:
    files = {
        name: (product / name).read_bytes()
        for name in ("capabilities.json", "proof.md", "changelog.md", "releases.json", "releases.feed.json", "releases.xml")
    }
    evidence = product / "docs" / "evidence"
    source = sorted(evidence.glob("software-benchmarks-*.json"))[-1]
    raw = source.read_bytes()
    report = json.loads(raw)
    guarded = report["guarded_cpu_request"]
    loop = report["event_loop_responsiveness"]
    intents = report["intent_dispatch"]
    risk = report["learned_risk_world_model"]
    tts_path = sorted(evidence.glob("local-tts-isolation-*.json"))[-1]
    tts = json.loads(tts_path.read_text(encoding="utf-8"))
    subscription_path = sorted(evidence.glob("subscription-planning-*.json"))[-1]
    subscription = json.loads(subscription_path.read_text(encoding="utf-8"))
    summary = {
        "captured_on": report["captured_on"],
        "source_commit": report["source_commit"],
        "source": RAW + source.name,
        "source_sha256": hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest(),
        "proof": "https://www.helioxos.dev/proof.md",
        "claim_boundary": report["claim_boundary"] + "; excludes UI rendering and full-workflow latency.",
        "guarded_local_request": {
            key: guarded["steady_state"][key] for key in ("iterations", "median_ms", "p95_ms", "p99_ms")
        } | {"model_calls": guarded["model_generate_calls"]},
        "event_loop_responsiveness": {
            key: loop[key] for key in ("heartbeat_ticks", "heartbeat_median_ms", "heartbeat_p95_ms", "heartbeat_max_ms")
        },
        "deterministic_intent_dispatch": {
            "passed": intents["passed"], "total": intents["case_count"], "median_ms": intents["latency"]["median_ms"]
        },
        "learned_risk_world_model": {
            key: risk[key] for key in ("model_version", "training_samples", "validation_samples", "learned_action_types")
        } | {"median_inference_ms": risk["inference"]["median_ms"]},
        "coadaptation_simulated_users": {
            key: report["coadaptation_simulated_users"][key]
            for key in ("evidence_kind", "scope", "families", "split", "in_sample", "claim_boundary", "protocol_sha256", "promoted_to_runtime", "limitations")
        } | {"agency_audits": {
            policy: audit["passed"] for policy, audit in report["coadaptation_simulated_users"]["agency_audit"].items()
        }},
        "local_tts_isolation": {
            "captured_on": tts["captured_on"],
            "engine": tts["environment"]["engine"],
            "cold_synthesis_seconds": tts["results"]["cold_synthesis_seconds"],
            "warm_synthesis_seconds": tts["results"]["warm_synthesis_seconds"],
            "parent_heavy_modules": tts["results"]["parent_torch_or_cuda_modules"],
            "idle_release_seconds": tts["environment"]["idle_timeout_seconds"],
            "source": RAW + tts_path.name,
            "results": tts["results"],
            "boundary": tts["claim_boundary"],
        },
        "subscription_planning": {
            "provider": subscription["provider"],
            "fixed_cases_passed": subscription["passed"],
            "fixed_cases_total": subscription["case_count"],
            "median_latency_seconds": subscription["median_latency_seconds"],
            "source": RAW + subscription_path.name,
            "scope": subscription["scope"],
            "boundary": subscription["claim_boundary"],
        },
    }
    files["benchmarks.json"] = raw
    files["lib/benchmark-evidence.js"] = (
        "// Generated by scripts/sync_product_evidence.py from the product evidence bundle.\n"
        "export default " + json.dumps(summary, indent=2, ensure_ascii=False) + ";\n"
    ).encode("utf-8")
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--product", type=Path, default=ROOT.parent / "cursor-os" / "pilot")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = outputs(args.product.resolve())
    drift = []
    for name, content in expected.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes().replace(b"\r\n", b"\n") != content.replace(b"\r\n", b"\n"):
                drift.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if drift:
        raise SystemExit("Product evidence drift: " + ", ".join(drift))
    print(f"{'Verified' if args.check else 'Synchronized'} {len(expected)} public evidence files.")


if __name__ == "__main__":
    main()
